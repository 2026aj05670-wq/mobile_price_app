import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os
from sklearn.metrics import(
    accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix
)
import seaborn as sns
import matplotlib.pyplot as plt

st.set_page_config(page_title = "Mobile Price Classification App", layout = "wide")

st.title("Mobile Price Classification & Evaluation Dashboard")
st.markdown("This app evaluates pre-trained machine learning models on uploaded test data without retraining.")

#Sidebar Configuration
st.sidebar.header("Configuration Panel")
uploaded_file = st.sidebar.file_uploader("Upload test_data.csv", type=["csv"])

model_options = {
    "Logistic_Regression": "model/logistic_regression_model.joblib",
    "Decision Tree": "model/decision_tree_model.joblib",
    "KNN": "model/knn_model.joblib",
    "Naive Bayes": "model/naive_bayes_model.joblib",
    "Support Vector Machine": "model/support_vector_machine_model.joblib"
}

selected_model_name = st.sidebar.selectbox("Select Classifier Model", list(model_options.keys()))

if uploaded_file is not None:
  test_df = pd.read_csv(uploaded_file)
  target_column = 'price_range'

  if target_column not in test_df.columns:
    st.error(f"Uploaded CSV must contain the target column named '{target_column}'.")
  else:
    x_test = test_df.drop(columns = [target_column])
    y_test = test_df[target_column]

    st.subheader(f"Evaluation Metrics for: {selected_model_name}")

    model_path = model_options[selected_model_name]

    if os.path.exists(model_path):
      model = joblib.load(model_path)

      #Predict
      y_pred = model.predict(x_test)
      try:
        y_prob = model.predict_proba(x_test)
        auc = roc_auc_score(y_test, y_prob, multi_class='ovr', average = 'weighted')
      except:
        auc = 0.0

      #Metrics
      acc = accuracy_score(y_test, y_pred)
      prec = precision_score(y_test, y_pred, average = 'weighted')
      rec = recall_score(y_test, y_pred, average = 'weighted')
      f1 = f1_score(y_test, y_pred, average = 'weighted')
      mcc = matthews_corrcoef(y_test, y_pred)

      #Dislpay Metric Cards
      c1, c2, c3 = st.columns(3)
      c1.metric("Accuracy", f"{acc:.4f}")
      c2.metric("AUC Score", f"{auc:.4f}")
      c3.metric("Precision", f"{prec:.4f}")

      c4, c5, c6 = st.columns(3)
      c4.metric("Recall", f"{rec:.4f}")
      c5.metric("F1 Score", f"{f1:.4f}")
      c6.metric("MCC Score", f"{mcc:.4f}")

      #Confusion Matrix Plot
      st.subheader("Confusion Matrix")
      fig, ax = plt.subplots(figsize=(6,4))
      sns.heatmap(confusion_matrix(y_test, y_pred), annot=True, fmt='d', cmap='Blues', ax=ax)
      ax.set_xlabel("Predicted Label")
      ax.set_ylabel("True Label")
      st.pyplot(fig)

    else:
      st.error(f"Model file not found at {model_path}.")

else:
  st.info("Please upload your test_data.csv file using the sidebar to begin evaluation.")
